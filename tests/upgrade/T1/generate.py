#!/usr/bin/env python3
"""T1: p + 12C -> 13N, capture and scattering.  Holds the true parameters and writes the project.

    python3 generate.py [path/to/AZURE2]      (or AZURE2_BIN / AZURE2_BINARY in the environment)

Writes T1.azr (the truth), T1_start.azr (the same model with the free parameters moved, the start of the
recovery fit), data/*.dat (the engine's observables at the truth with Gaussian noise, seed SEED) and
temperatures.dat.  The data depend on the engine that computes the truth; the files committed were made with the
engine named in README.md, and are not regenerated by any test.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "lib"))
import upgrade_project as up  # noqa: E402

SEED = 13
M = up.MASS
S_P = up.separation(M["p"], M["12C"], M["13N"])     # 1.94350 MeV
R = 3.6                                               # channel radius (fm)


def model():
    p12c = up.Pair(1, 0.5, 1, 0.0, 1, M["p"], M["12C"], 1, 6, S_P, ptype=0, R=R, g1=5.5856946893, g2=0.0)
    # gamma pairs: to the 1/2- ground state and to a FICTITIOUS bound 3/2- state at 1.0 MeV (13N has no bound
    # excited state; this one exists so capture to an excited state, with its own ANC, is covered).
    g0 = up.Pair(2, 1.0, 1, 0.5, -1, 0.0, M["13N"], 0, 7, 0.0, ptype=10, R=0.0, ecmask=7)
    g1 = up.Pair(3, 1.0, 1, 1.5, -1, 0.0, M["13N"], 0, 7, 0.0, ptype=10, R=0.0, e2=1.0, ecmask=7)
    C = up.Channel
    levels = [
        # bound final states: ANC (fm^-1/2) of the p-wave, s = 1/2
        up.Level(0.5, -1, 0.0, [C(p12c, 1, 2, 1.85, fixed=False)], name="1/2- g.s."),
        up.Level(1.5, -1, 1.0, [C(p12c, 1, 2, 1.20, fixed=False)], name="3/2- 1.0 (fictitious)"),
        # 1/2+ s-wave resonance, E1 to both bound states (Brune observed widths, eV)
        up.Level(0.5, 1, 2.3650, [C(p12c, 1, 0, 33000.0, fixed=False),
                                  C(g0, 1, 2, 0.45, fixed=False),
                                  C(g1, 3, 2, 0.10, fixed=False)], fixed=False, name="1/2+ 2.365"),
        # 3/2- p-wave resonance: M1 to the g.s. and to the 3/2- state.  Every nonzero photon width is free: a
        # photon width in the .azr is an observed width whose external part depends on the final state's ANC, so a
        # FIXED nonzero one would move with a fitted ANC (and the start model would not be the truth with only the
        # free parameters moved).  The resonant E2 to the g.s. is zero (E2 enters through external capture).
        up.Level(1.5, -1, 3.5020, [C(p12c, 1, 2, 55000.0, fixed=False),
                                   C(g0, 1, 2, 0.50, fixed=False),
                                   C(g0, 1, 4, 0.0),
                                   C(g1, 3, 2, 0.20, fixed=False)], fixed=False, name="3/2- 3.502"),
        # 5/2+ d-wave resonance: E1 to the 3/2- state
        up.Level(2.5, 1, 3.5470, [C(p12c, 1, 4, 47000.0, fixed=False),
                                  C(g1, 3, 2, 0.05, fixed=False)], fixed=False, name="5/2+ 3.547"),
        # background poles (fixed)
        up.Level(0.5, 1, 15.0, [C(p12c, 1, 0, 3.0e6)], name="1/2+ background"),
        up.Level(1.5, -1, 15.0, [C(p12c, 1, 2, 2.0e6)], name="3/2- background"),
    ]
    S = up.DataSegment
    elastic_e = up.grid(0.30, 2.00, 0.025)
    data = [
        S("el_lab090", 1, 1, 1, [(e, 90.0) for e in elastic_e], ("rel", 0.02), amin=90, amax=90),
        S("el_lab125", 1, 1, 1, [(e, 125.0) for e in elastic_e], ("rel", 0.02), amin=125, amax=125),
        S("el_lab160", 1, 1, 1, [(e, 160.0) for e in elastic_e], ("rel", 0.02), amin=160, amax=160),
        S("ay_cm090", 1, 1, 7, [(e, 90.0) for e in up.grid(1.55, 1.90, 0.01)], ("abs", 0.02), amin=90, amax=90),
        S("ay_cm150", 1, 1, 7, [(e, 150.0) for e in up.grid(1.55, 1.90, 0.01)], ("abs", 0.02), amin=150, amax=150),
        S("phase_s12", 1, 1, 2, [(e, 0.0) for e in up.grid(0.30, 2.00, 0.05)], ("abs", 0.5), phase_jl=(0.5, 0),
          keep=lambda t: abs(t) < 75.0),
        S("cap_g0", 1, 2, 0, [(e, 0.0) for e in up.grid(0.12, 2.00, 0.04)], ("rel", 0.05)),
        S("cap_g1", 1, 3, 0, [(e, 0.0) for e in up.grid(0.15, 2.00, 0.05)], ("rel", 0.05)),
        S("cap_g0_lab000", 1, 2, 1, [(e, 0.0) for e in up.grid(1.40, 2.00, 0.03)], ("rel", 0.05), amin=0, amax=0),
        S("cap_g0_lab090", 1, 2, 1, [(e, 90.0) for e in up.grid(1.40, 2.00, 0.03)], ("rel", 0.05), amin=90,
          amax=90),
    ]
    T = up.TestSegment
    tests = [
        T(1, 2, 0.02, 0.60, 0.02),                 # S factor / cross section to the g.s., extrapolated down
        T(1, 3, 0.02, 0.60, 0.02),                 # to the 3/2- state
        T(1, 1, 0.30, 2.00, 0.05, isdiff=2, extra="0.5 0"),    # s1/2 phase shift
        T(1, 1, 0.30, 2.00, 0.05, isdiff=2, extra="1.5 1"),    # p3/2 phase shift
        T(1, 2, 1.50, 1.90, 0.10, 0.0, 180.0, 30.0, isdiff=1),  # capture angular distribution
    ]
    return up.Project("T1", [p12c, g0, g1], levels, data, tests, rate=(1, 2))


# The start of the recovery fit: each free parameter moved by this factor (energies by an offset in MeV).
START_SHIFT = {"E": 0.004, "W": 1.15}


def start_model():
    m = model()
    for _, ref in m.free_parameters():
        v = m.get(ref)
        m.set(ref, v + START_SHIFT["E"] if ref[0] == "E" else v * START_SHIFT["W"])
    return m


def main():
    binary = up.find_binary(sys.argv[1] if len(sys.argv) > 1 else None)
    m = model()
    truth = up.truth_values(binary, m)
    for seg in m.data:                    # drop points by the segment's rule (phase shifts near +-90 deg)
        if seg.keep is not None:
            keep = [seg.keep(t) for t in truth[seg.name]]
            seg.points = [p for p, k in zip(seg.points, keep) if k]
            truth[seg.name] = truth[seg.name][keep]
    data = up.synthesize(m, truth, SEED)
    for seg in m.data:
        kind, size = seg.noise
        hdr = (f"# T1 synthetic data ({seg.name}), generate.py: engine truth + Gaussian noise "
               f"({'%g %%' % (100 * size) if kind == 'rel' else '%g absolute' % size}), seed {SEED}\n"
               "# E_lab (MeV)  angle (deg)  value  uncertainty   [lab frame unless the segment is c.m. (A_y)]\n")
        up.write_data(os.path.join(HERE, "data", seg.name + ".dat"), data[seg.name], seg, hdr)
    m.write(HERE, binary)                    # after the data files: the converter reads them
    start_model().write(HERE, binary, "T1_start")
    with open(os.path.join(HERE, "temperatures.dat"), "w") as f:
        f.write("0.01\n0.03\n0.1\n0.3\n1.0\n3.0\n")
    n = sum(len(s.points) for s in m.data)
    print(f"T1: {len(m.data)} segments, {n} points, {len(m.free_parameters())} free parameters")


if __name__ == "__main__":
    main()

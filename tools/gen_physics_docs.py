#!/usr/bin/env python3
"""Write the user-guide page of the physics functions from the rows of the binding's table.

    PYAZR_ENGINE_DIR=<build>/pyazr-out python3 tools/gen_physics_docs.py [--check]

The page, docs/source/user_guide/physics_functions.rst, is the table's (api/src/pybind_physics.cpp, read through
``pyazr.kinds()["physics"]``), never prose that can drift: a new row appears after one run of this script.
``--check`` writes nothing and exits 1 when the page differs from what the rows give (tests/pyazr/physics_table_test.py
runs it).
"""
import os
import sys
import textwrap

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
PAGE = os.path.join(ROOT, "docs", "source", "user_guide", "physics_functions.rst")

HEADER = """.. This page is generated by tools/gen_physics_docs.py from the binding's physics table
   (api/src/pybind_physics.cpp); edit the rows, not this file.

Physics functions (``pyazr.physics``)
=====================================

Each function below evaluates one function of the engine's libraries (``physics/``, ``experiment/``) element by
element, without a project or a session.  Arguments broadcast against each other (numpy rules); scalars in give
scalars out.  A function with one returned field returns it; one with several returns a dict.  An element outside
the domain raises ``pyazr.DomainError`` naming the argument, its value and the domain; ``errors="mask"`` returns NaN
there and ``(result, status)`` instead, status 0 computed, k > 0 argument k outside its domain, -2 the arguments
together outside the domain, -1 not converged (``pyazr.physics.status_text`` says it in words).  The same rows are
``pyazr.kinds()["physics"]``.

.. code-block:: python

   import numpy as np, pyazr
   e = np.linspace(0.1, 2.0, 50)                                     # MeV, c.m.
   P = pyazr.physics.penetrability(1, 1, 6, 1.00728, 12.0, 5.0, e)   # p + 12C, l = 1, a = 5 fm
   P, status = pyazr.physics.penetrability(1, 1, 6, 1.00728, 12.0, 5.0, e - 1.0, errors="mask")

Functions that need a session's level scheme are methods of the session: ``channel_functions(pair, e_cm, l)``
(the session's Coulomb table, GSL or hybrid potential included).

"""


def esc(text):
    return text.replace("*", r"\*").replace("|", r"\|")


def generate(rows):
    out = [HEADER]
    for name, row in rows.items():
        args = ", ".join(a["name"] + ("" if a["default"] is None else f"={a['default']!r}") for a in row["arguments"])
        title = f"``{name}({args})``"
        out.append(title + "\n" + "-" * len(title) + "\n\n")
        out.append(textwrap.fill(esc(row["summary"]) + "  " + esc(row["doc"]), 120) + "\n\n")
        out.append(f"Library: ``{row['library']}``.  Plot axis: ``{row['axis']}``.\n\n")
        out.append(".. list-table::\n   :header-rows: 1\n\n   * - argument\n     - unit\n     - domain\n     - meaning\n")
        for a in row["arguments"]:
            out.append(f"   * - ``{a['name']}``\n     - {a['unit'] or '--'}\n     - {esc(a['domain'])}\n"
                       f"     - {esc(a['doc'])}\n")
        out.append("\n.. list-table::\n   :header-rows: 1\n\n   * - returns\n     - unit\n     - meaning\n")
        for r in row["returns"]:
            out.append(f"   * - ``{r['name']}``\n     - {r['unit'] or '--'}\n     - {esc(r['doc'])}\n")
        out.append("\n")
    return "".join(out).rstrip("\n") + "\n"


def main():
    sys.path.insert(0, ROOT)
    import pyazr
    text = generate(pyazr.kinds()["physics"])
    if "--check" in sys.argv[1:]:
        with open(PAGE) as f:
            same = f.read() == text
        print("physics_functions.rst is the table's" if same else
              "docs/source/user_guide/physics_functions.rst differs from the rows: run tools/gen_physics_docs.py")
        return 0 if same else 1
    with open(PAGE, "w") as f:
        f.write(text)
    print(f"wrote {PAGE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

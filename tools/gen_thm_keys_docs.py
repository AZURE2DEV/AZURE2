#!/usr/bin/env python3
"""Write docs/source/reference/thm_keys.rst from the engine's table of the <thm> keys (pyazr.kinds()["thm"], read
from src/ThmKeys.cpp).  Needs the engine module (PYAZR_ENGINE_DIR); tests/pyazr/thm_keys_test.py fails while the page
is not what this writes.

    python3 tools/gen_thm_keys_docs.py            # write the page
"""
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
PAGE = os.path.join(ROOT, "docs", "source", "reference", "thm_keys.rst")


def _text(s):
    """Prose of a row as reStructuredText: | and * are literal."""
    return s.replace("\\", "\\\\").replace("|", "\\|").replace("*", "\\*").replace("`", "\\`")


def _value(f):
    if f.get("values"):
        return " | ".join(f"``{v}``" for v in f["values"])
    if f.get("grammar"):
        return f"``{f['grammar']}``"
    return f["type"] + (f" ({f['unit']})" if f.get("unit") else "")


def generate(thm, nuclides, opticals):
    out = [".. This page is generated by tools/gen_thm_keys_docs.py from the engine's table of the <thm> keys",
           "   (src/ThmKeys.cpp, pyazr.kinds()[\"thm\"]).  Do not edit it: change the table and regenerate.", "",
           "The ``<thm>`` keys: the table", "==============================", "",
           "The engine reads every key of the ``<thm>`` section by its row of one table: the global options, and the "
           "keys of an ``experiment[<name>]`` line.  ``pyazr.kinds()[\"thm\"]`` returns the same rows as two record "
           "kinds; ``Project.set_thm`` and ``Project.set_thm_experiment`` write them, and the engine refuses a key "
           "or value the table does not take.  The physics of each key: :doc:`../theory/thm_implementation`.", ""]
    for kind in thm.values():
        title = kind["title"]
        out += [title, "-" * len(title), "", _text(kind["doc"]), "", ".. list-table::", "   :header-rows: 1",
                "   :widths: 18 30 12 40", "", "   * - key", "     - value", "     - default", "     - meaning"]
        for key, f in kind["fields"].items():
            doc = _text(f["doc"])
            if f.get("applies_when"):
                doc += f"; applies when {f['applies_when']['text']}"
            out += [f"   * - ``{key}``", f"     - {_value(f)}",
                    f"     - ``{f['default']}``" if f.get("default") else "     -", f"     - {doc}"]
        out.append("")
    out += ["Built-in nuclei", "---------------", "",
            "A nucleus of ``beam=``, ``target=`` or ``spectator=`` is one of these names (nuclear masses of AME2020, "
            "``pyazr.kinds()[\"nuclides\"]``) or ``Z,A,mass`` with the nuclear mass in u: " +
            ", ".join(f"``{n}``" for n in nuclides) + ".", "",
            "Global optical potentials", "-------------------------", "",
            "``opticalAA=`` and ``opticalSF=`` take these names (``pyazr.kinds()[\"optical_potentials\"]``), "
            "``:extrapolate`` to use one outside the target masses and lab energies of its fit.", "",
            ".. list-table::", "   :header-rows: 1", "   :widths: 15 25 20 40", "",
            "   * - name", "     - projectiles", "     - A, E (MeV)", "     - reference"]
    for name, g in opticals.items():
        out += [f"   * - ``{name}``", f"     - {_text(str(g['projectiles']))}",
                f"     - {g['a_range'][0]:g}-{g['a_range'][1]:g}, {g['e_range'][0]:g}-{g['e_range'][1]:g}",
                f"     - {_text(g['reference'])}"]
    out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    sys.path.insert(0, ROOT)
    import pyazr
    with open(PAGE, "w") as f:
        k = pyazr.kinds()
        f.write(generate(k["thm"], k["nuclides"], k["optical_potentials"]))
    print(f"wrote {PAGE}")

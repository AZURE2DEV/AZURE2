#!/usr/bin/env python3
"""Write docs/source/reference/format3.rst from the table of project format 3.

The table lives in the engine (experiment/src/Schema.cpp, Quantities.cpp, Units.cpp, Diagnostics.cpp); its JSON
export is committed as tests/schema/schema_v3.json (check 21; regenerate it with
AZURE2 --schema-out=tests/schema/schema_v3.json, not with a redirect of --schema, which empties the file when the
binary fails).  This script turns that JSON into
the reference page, so the page cannot say anything the table does not (docs/upgrade/project_format3.md section
7.3).  The generated page is committed; repo_consistency check 18 fails when it differs from this script's output.

    python3 tools/gen_schema_docs.py            # rewrite docs/source/reference/format3.rst
    python3 tools/gen_schema_docs.py --check    # exit 1 if the committed page is not the generated one
    python3 tools/gen_schema_docs.py --schema other.json --out page.rst

Pure standard library.
"""

import argparse
import json
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SCHEMA = os.path.join(ROOT, "tests", "schema", "schema_v3.json")
OUT = os.path.join(ROOT, "docs", "source", "reference", "format3.rst")


def esc(text):
    """Plain text safe in reStructuredText: no emphasis, interpreted text, substitutions or references."""
    text = text.replace("\\", "\\\\")
    for c in "*`|":
        text = text.replace(c, "\\" + c)
    # a word ending in "_" is a reference: before a space, the end or any punctuation ("[A-Za-z0-9_-]" was read as
    # the target "a-za-z0-9": an error of the Sphinx build)
    return re.sub(r"_(?=\W|$)", r"\\_", text)


def lit(text):
    """Inline literal; an empty string becomes an em dash."""
    return f"``{text}``" if text else "--"


def condition(c):
    return esc(c["text"]) if c else ""


def table(header, rows, widths):
    out = [".. list-table::", "   :header-rows: 1", f"   :widths: {' '.join(str(w) for w in widths)}", ""]
    for row in [header] + rows:
        for i, cell in enumerate(row):
            lines = str(cell).split("\n") if cell != "" else [""]
            out.append((("   * - " if i == 0 else "     - ") + lines[0]).rstrip())
            out.extend("       " + extra for extra in lines[1:])
    return out + [""]


def heading(text, char):
    return [text, char * len(text), ""]


def field_presence(f):
    if f.get("by_quantity"):
        return "by quantity"
    parts = []
    if "applies_when" in f:
        parts.append("only when " + condition(f["applies_when"]))
    if "required_when" in f:
        parts.append("required when " + condition(f["required_when"]))
    elif f.get("required"):
        parts.append("required")
    else:
        parts.append("optional" + (f" (default {lit(f['default'])})" if "default" in f else ""))
    if f.get("repeatable"):
        parts.append("repeatable")
    return "; ".join(parts)


def generate(schema):
    out = [".. This page is generated by tools/gen_schema_docs.py from tests/schema/schema_v3.json (AZURE2 --schema).",
           "   Do not edit it: change the table in experiment/src/ and regenerate (repo_consistency check 18).", ""]
    out += heading("Project format 3: the table", "=")
    out += [
        f"Schema version {lit(schema['schema_version'])}.  A format-3 project describes each data set, target, beam, "
        "detector, shared normalization, energy scale, extrapolation and model datum as one record: a header line "
        "``<kind> <name>`` followed by one ``<key> <value>`` line per field, inside the section that holds the kind.  "
        "``#`` starts a comment; a token with blanks is quoted; indentation is not significant.  Every closed choice "
        "below is a row of one table compiled into the engine; ``AZURE2 --schema`` prints it as JSON and "
        "``pyazr.schema()`` returns it as a dict.  ``AZURE2 --validate FILE`` (``pyazr.validate(path)``) checks a "
        "project against it and reports every problem; ``AZURE2 --convert OLD NEW`` "
        "(``pyazr.convert_azr(old, new)``) writes an older project in this format (:doc:`../user_guide/older_projects`).  The design is "
        "``docs/upgrade/project_format3.md``.",
        "",
        "Names are ``[A-Za-z][A-Za-z0-9_-]*`` and unique across the project; a field names another record by its name.  "
        "Within a section, record kinds and field keys are disjoint, so a line is a header or a field by its first word.",
        ""]

    out += heading("Sections", "-")
    out += table(["section", "record kinds"],
                 [[lit(f"<{s}>"), ", ".join(lit(k) for k in kinds)] for s, kinds in schema["sections"].items()], [20, 80])

    out += heading("Value types", "-")
    out += table(["type", "grammar", "meaning"],
                 [[lit(t), lit(v.get("grammar", "")), esc(v["doc"])] for t, v in schema["value_types"].items()],
                 [15, 45, 40])

    out += heading("Records", "-")
    for kind, rec in schema["records"].items():
        out += heading(f"{kind}", "~")
        out += [f"{esc(rec['title'])}, in {', '.join(lit('<' + s + '>') for s in rec['sections'])}.  {esc(rec['doc'])}", ""]
        rows = []
        for key, f in rec["fields"].items():
            rows.append([lit(key), lit(f["grammar"]), field_presence(f), esc(f["doc"])])
        out += table(["field", "value", "presence", "meaning"], rows, [14, 40, 22, 24])
        if rec.get("one_of"):
            out += ["At least one of: " + "; ".join(", ".join(lit(k) for k in g) for g in rec["one_of"]) + ".", ""]
        if rec.get("refused"):
            out += ["Refused here: " + "; ".join(f"{lit(k)} ({esc(v)})" for k, v in rec["refused"].items()) + ".", ""]
        if rec.get("deleted"):
            out += ["Deleted from format 3 (``E_FIELD_DELETED``): " +
                    "; ".join(f"{lit(k)} ({esc(v)})" for k, v in rec["deleted"].items()) + ".", ""]

    out += heading("Quantities", "-")
    out += ["``quantity`` of a ``dataset``, ``extrapolation`` or ``datum``.  The units of the value column are listed with "
            "their factor to the quantity's engine unit (-- where the factor needs the charge state or the efficiency, "
            "or for arbitrary units).  Fields not listed under a quantity are refused for it.", ""]
    for name, q in schema["quantities"].items():
        out += heading(name, "~")
        aliases = f"  Aliases: {', '.join(lit(a) for a in q['aliases'])}." if q.get("aliases") else ""
        out += [f"{esc(q['title'])} ({', '.join(lit(k) for k in q['record_kinds'])}).  {esc(q['doc'])}{aliases}", ""]
        units = ", ".join(f"{lit(u)} ({'--' if f is None else f'{f:g}'})" for u, f in q["units"].items())
        rows = [["engine unit", lit(q["engine_unit"])], ["units", units]]
        for c in q.get("unit_conditions", []):
            what = c.get("unit") or c.get("dimension")
            rows.append(["", f"{lit(what)} only when {condition(c['when'])}"])
        cols = q["columns"]
        rows.append(["energy column", ", ".join(lit(r) for r in cols["energy"]) or "--"])
        if cols["angle_axis"] != "none":
            rows.append(["angle column", f"{cols['angle_axis']}: " + ", ".join(lit(r) for r in cols["angle"])])
        if cols["order"]:
            rows.append(["order column", "required"])
        if cols["windows"]:
            rows.append(["window columns", "allowed (a beam with a profile)"])
        if q["reaction"]["rule"] or q["reaction"]["flags"]:
            rows.append(["reaction", esc(q["reaction"]["rule"]) or ", ".join(q["reaction"]["flags"])])
        for f, r in q["fields"].items():
            when = f" when {condition(r['when'])}" if "when" in r else ""
            rows.append([lit(f), ("required" if r["required"] else "allowed") + when])
        if q.get("target_kinds"):
            rows.append(["target kinds", ", ".join(lit(k) for k in q["target_kinds"])])
        for r in q.get("norm_rules", []):
            rows.append(["norm", f"{', '.join(r['modes'])} when {condition(r['when'])}: {esc(r['message'])}"])
        rows.append(["tree", lit(q["tree"])])
        if q["exfor"]:
            rows.append(["EXFOR", ", ".join(lit(e) for e in q["exfor"])])
        for r in q["refusals"]:
            rows.append([f"refused ({r['checked_by']})", f"{esc(r['rule'])}: {esc(r['message'])} ({lit(r['code'])})"])
        out += table(["property", "value"], rows, [20, 80])
    rules = schema.get("general_norm_rules", [])
    if rules:
        out += ["For every quantity: " + "; ".join(
            f"norm {', '.join(r['modes'])} when {condition(r['when'])} ({esc(r['message'])})" for r in rules) + ".", ""]

    out += heading("Units", "-")
    out += ["A value written in a unit is multiplied by its factor to give the engine unit of its dimension.  There is "
            "no default unit.", ""]
    out += table(["unit", "dimension", "factor", "engine unit", "aliases"],
                 [[lit(u), lit(v["dimension"]), f"{v['factor']:g}", lit(v["engine_unit"]),
                   ", ".join(lit(a) for a in v.get("aliases", []))] for u, v in schema["units"].items()],
                 [20, 22, 14, 20, 24])

    out += heading("Column roles", "-")
    out += table(["role", "unit"], [[lit(r), f"{lit(v['unit'])} unit in brackets" if v["unit"] else "--"]
                                    for r, v in schema["column_roles"].items()], [30, 70])

    out += heading("Diagnostic codes", "-")
    out += ["``AZURE2 --validate`` and ``pyazr`` report every problem with one of these codes, the line and column, "
            "the record and field, what was found and what is allowed; a fix, when given, changes syntax only.", ""]
    out += table(["code", "severity", "meaning"],
                 [[lit(c), v["severity"], esc(v["meaning"])] for c, v in schema["diagnostic_codes"].items()],
                 [30, 10, 60])
    while out and out[-1] == "":
        out.pop()
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--schema", default=SCHEMA)
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--check", action="store_true", help="exit 1 if the page differs from the generated text")
    args = ap.parse_args()
    with open(args.schema, encoding="utf-8") as f:
        text = generate(json.load(f))
    if args.check:
        try:
            with open(args.out, encoding="utf-8") as f:
                same = f.read() == text
        except OSError:
            same = False
        if not same:
            print(f"{args.out} is not the output of tools/gen_schema_docs.py; regenerate it")
        return 0 if same else 1
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
